"""Serve the manual speaker-echo probe (aec_probe.html) on an ephemeral localhost port.

    python tests/voice_v0/manual/aec_manual_server.py

Prints a http://127.0.0.1:<port>/aec_probe.html URL and serves a ~25 s synthetic
Kokoro stimulus at /stimulus.wav (generated by tests/voice_v0/make_fixtures.py;
run that first). It listens on 127.0.0.1 only, never on 8402/8403/8405, and writes
nothing. Open the URL in the SAME Chrome that runs the HUD (Windows Chrome reaches
WSL localhost). getUserMedia works on http://127.0.0.1 without TLS.
"""

from __future__ import annotations

import http.server
import io
import sys
import wave
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import common  # noqa: E402

HERE = Path(__file__).resolve().parent


def stimulus() -> bytes:
    clips = [c for c in common.load_manifest() if c["engine"] == "kokoro"]
    out, n, i = [], 0, 0
    while n < 25 * common.SR:
        x = common.read_wav(common.FIXTURES / clips[(i * 5) % len(clips)]["file"])
        out += [x, np.zeros(int(0.3 * common.SR), np.float32)]
        n += len(x) + int(0.3 * common.SR)
        i += 1
    x = np.concatenate(out)[: 25 * common.SR]
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(common.SR)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())
    return buf.getvalue()


def main() -> int:
    data = stimulus()

    class H(http.server.SimpleHTTPRequestHandler):
        def do_GET(self):
            if self.path.startswith("/stimulus.wav"):
                self.send_response(200)
                self.send_header("Content-Type", "audio/wav")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)
            elif self.path.startswith("/aec_probe.html"):
                body = (HERE / "aec_probe.html").read_bytes()
                self.send_response(200)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            else:
                self.send_error(404)

        def log_message(self, *a):
            pass

    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), H)
    print(f"open http://127.0.0.1:{srv.server_address[1]}/aec_probe.html  (Ctrl+C to stop)", flush=True)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
